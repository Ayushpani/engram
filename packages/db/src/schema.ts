export const memories = pgTable(
	"memories",
	{
		id: text("id").primaryKey(),
		tenantId: text("tenant_id")
			.notNull()
			.references(() => tenants.id, { onDelete: "cascade" }),
		userId: text("user_id"),
		sessionId: text("session_id"),
		text: text("text").notNull(),
		kind: text("kind", { enum: ["fact", "preference", "event", "entity"] })
			.notNull()
			.default("fact"),
		source: text("source", { enum: ["text", "voice"] })
			.notNull()
			.default("text"),
		embedding: vector("embedding", { dimensions: EMBED_DIM }),
		metadata: jsonb("metadata").notNull().default(sql`'{}'::jsonb`),
		createdAt: timestamp("created_at", { withTimezone: true })
			.notNull()
			.defaultNow(),
		updatedAt: timestamp("updated_at", { withTimezone: true })
			.notNull()
			.defaultNow(),

		// Bi-temporal validity. validUntil = NULL means "still current". A
		// correction closes out the prior row (validUntil = now()) and
		// links the new one via supersedesId, in one transaction — see
		// core.ts save()'s `revises` path.
		validFrom: timestamp("valid_from", { withTimezone: true })
			.notNull()
			.defaultNow(),
		validUntil: timestamp("valid_until", { withTimezone: true }),
		supersedesId: text("supersedes_id"),

		// Beta-Binomial belief: confidence = alpha / (alpha + beta). Starts
		// at Beta(1,1) — a uniform, neutral prior — and is updated by
		// packages/core/src/belief.ts as corroborating/contradicting
		// evidence arrives across sessions.
		confidenceAlpha: real("confidence_alpha").notNull().default(1),
		confidenceBeta: real("confidence_beta").notNull().default(1),

		// Recency x frequency decay inputs for the temporal RRF channel.
		accessCount: integer("access_count").notNull().default(0),
		lastAccessedAt: timestamp("last_accessed_at", { withTimezone: true }),

		// Generated by Postgres (migration 0002) — see tsvectorType above.
		textTsv: tsvectorType("text_tsv"),
	},
	(t) => ({
		tenantIdx: index("memories_tenant_idx").on(t.tenantId),
		sessionIdx: index("memories_session_idx").on(t.sessionId),
		userIdx: index("memories_user_idx").on(t.userId),
		embedHnsw: index("memories_embedding_hnsw")
			.using("hnsw", t.embedding.op("vector_cosine_ops"))
			.with({ m: 16, ef_construction: 64 }),
		currentIdx: index("memories_tenant_user_current_idx")
			.on(t.tenantId, t.userId, t.validUntil)
			.where(sql`valid_until IS NULL`),
	}),
)

export const entities = pgTable(
	"entities",
	{
		id: text("id").primaryKey(),
		tenantId: text("tenant_id")
			.notNull()
			.references(() => tenants.id, { onDelete: "cascade" }),
		name: text("name").notNull(),
		kind: text("kind").notNull(),
		metadata: jsonb("metadata").notNull().default(sql`'{}'::jsonb`),
		createdAt: timestamp("created_at", { withTimezone: true })
			.notNull()
			.defaultNow(),
	},
	(t) => ({
		tenantNameIdx: index("entities_tenant_name_idx").on(t.tenantId, t.name),
		nameTrgmIdx: index("entities_name_trgm_idx")
			.using("gin", sql`${t.name} gin_trgm_ops`),
	}),
)

