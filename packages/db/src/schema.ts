import { sql } from "drizzle-orm"
import {
	customType,
	index,
	integer,
	jsonb,
	pgTable,
	real,
	text,
	timestamp,
	uniqueIndex,
	vector,
} from "drizzle-orm/pg-core"

export const EMBED_DIM = 1536

/**
 * float4[] fallback exposed as `Float32Array` for cases where pgvector
 * is unavailable at query time. The primary column stays `vector`.
 */
export const float4Array = customType<{ data: number[]; driverData: string }>({
	dataType() {
		return "real[]"
	},
})

/**
 * Read-only handle onto the `text_tsv` generated column (added by
 * migration 0002, `GENERATED ALWAYS AS (to_tsvector('simple', text))
 * STORED`). Postgres computes and maintains it — the app never writes it,
 * so this type only needs to be selectable/filterable, not insertable.
 */
export const tsvectorType = customType<{ data: unknown }>({
	dataType() {
		return "tsvector"
	},
})

export const tenants = pgTable("tenants", {
	id: text("id").primaryKey(),
	name: text("name").notNull(),
	createdAt: timestamp("created_at", { withTimezone: true })
		.notNull()
		.defaultNow(),
})

export const apiKeys = pgTable(
	"api_keys",
	{
		id: text("id").primaryKey(),
		tenantId: text("tenant_id")
			.notNull()
			.references(() => tenants.id, { onDelete: "cascade" }),
		hashedKey: text("hashed_key").notNull(),
		label: text("label"),
		createdAt: timestamp("created_at", { withTimezone: true })
			.notNull()
			.defaultNow(),
		revokedAt: timestamp("revoked_at", { withTimezone: true }),
	},
	(t) => ({
		hashedKeyIdx: uniqueIndex("api_keys_hashed_key_idx").on(t.hashedKey),
		tenantIdx: index("api_keys_tenant_idx").on(t.tenantId),
	}),
)

